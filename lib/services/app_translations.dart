  /// Translate key according to currently active language in SessionManager
  static String tr(String key) {
    final lang = SessionManager().language;
    final dict = _localizedValues[lang] ?? _localizedValues['en']!;
    return dict[key] ?? _localizedValues['en']?[key] ?? key;
  }

  static String getLanguageName(String code) {
    for (final opt in supportedLanguages) {
      if (opt.code == code) return opt.nativeName;
    }
    return 'English';
  }
